#!/usr/bin/env bash
# ==============================================================================================
# gen-layouts.sh - (re)generate codebrix-wgpu/src/layouts.rs, the struct table behind
#                  wgpuCodebrixGetStructLayout
# ==============================================================================================
#
#   ./gen-layouts.sh            write codebrix-wgpu/src/layouts.rs
#   ./gen-layouts.sh --check    exit 1 unless the committed file is what this script writes
#
# The table lists EVERY struct defined in the three C headers the library implements:
#   wgpu-native/ffi/webgpu-headers/webgpu.h   (webgpu.yml)
#   wgpu-native/ffi/wgpu.h                    (wgpu-native's extensions)
#   codebrix-wgpu/include/codebrix_wgpu.h     (specs/codebrix.yml)
# A struct is a `typedef struct WGPUName ... { ... } WGPUName` definition (handle typedefs such as
# `typedef struct WGPUDeviceImpl* WGPUDevice` are not structs and are skipped). The webgpu.h /
# wgpu.h types come from wgpu-native's bindgen output (wgpu_native::native::*); the codebrix ones
# are the #[repr(C)] structs of codebrix-wgpu/src/codebrix.rs. The Rust compiler then reports the
# real size_of / align_of for the target, so the table is right on every RID by construction.
# Run it after an upstream bump (refresh-upstream.sh says so) or a codebrix.yml change.
# Needs only bash, awk, sort. Reads only this repository.
# ==============================================================================================
set -euo pipefail

TOOLS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$TOOLS_DIR/codebrix-wgpu/src/layouts.rs"

structs_of() {
    awk '
        /^typedef struct WGPU[A-Za-z0-9_]+[ \t]*\{?[ \t]*$/ { inside = 1; next }
        inside && /^\}[ \t]*WGPU[A-Za-z0-9_]+/ { name = $2; sub(/[;].*/, "", name); print name; inside = 0 }
    ' "$1"
}

generate() {
    local core native codebrix
    core="$(structs_of "$TOOLS_DIR/wgpu-native/ffi/webgpu-headers/webgpu.h" | LC_ALL=C sort -u)"
    native="$(structs_of "$TOOLS_DIR/wgpu-native/ffi/wgpu.h" | LC_ALL=C sort -u)"
    codebrix="$(structs_of "$TOOLS_DIR/codebrix-wgpu/include/codebrix_wgpu.h" | LC_ALL=C sort -u)"
    echo "// GENERATED by tools-scripts/gen-layouts.sh - DO NOT EDIT. Re-run the script instead."
    echo "//"
    echo "// Every struct of webgpu.h ($(printf '%s\n' "$core" | grep -c .)), wgpu.h ($(printf '%s\n' "$native" | grep -c .)) and codebrix_wgpu.h ($(printf '%s\n' "$codebrix" | grep -c .)), sorted by C name,"
    echo "// with the size and alignment the compiler gives it on the target being built."
    echo
    echo "use std::mem::{align_of, size_of};"
    echo
    echo "use crate::codebrix::*;"
    echo "use wgpu_native::native::*;"
    echo
    echo "/// (C type name, size_of, align_of) of every struct the library's headers declare."
    echo "pub static STRUCT_LAYOUTS: &[(&str, usize, usize)] = &["
    printf '%s\n%s\n%s\n' "$core" "$native" "$codebrix" | grep . | LC_ALL=C sort -u | while read -r s; do
        echo "    (\"$s\", size_of::<$s>(), align_of::<$s>()),"
    done
    echo "];"
}

case "${1:-}" in
    --check) cmp -s "$OUT" <(generate) || { echo "ERROR: $OUT is stale - run tools-scripts/gen-layouts.sh" >&2; exit 1; }
             echo "layouts.rs is current" ;;
    "")      generate > "$OUT"; echo "wrote $OUT ($(grep -c 'size_of::<' "$OUT") structs)" ;;
    *)       echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
