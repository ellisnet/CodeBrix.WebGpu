using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using CodeBrix.Templating;
using CodeBrix.Templating.Runtime;
using CodeBrix.WebGpu.BindingGenerator.Model;

namespace CodeBrix.WebGpu.BindingGenerator.Rendering;

/// <summary>Renders the model through the embedded Scriban templates.</summary>
public sealed class CSharpRenderer
{
    /// <summary>The relative path (from the repository root) of the generated C# folder.</summary>
    public const string GeneratedFolder = "src/CodeBrix.WebGpu.Native/Generated";

    /// <summary>The relative path (from the repository root) of the expected-exports list.</summary>
    public const string ExpectedExportsPath = "wgpu-native-tools/specs/expected-exports.txt";

    private readonly ApiModel model;
    private readonly DocWriter docs;
    private readonly IReadOnlyList<KeyValuePair<string, string>> inputHashes;

    /// <summary>Creates a renderer.</summary>
    /// <param name="model">The model.</param>
    /// <param name="inputHashes">The inputs (relative path, sha256 hex) listed in every banner.</param>
    public CSharpRenderer(ApiModel model, IReadOnlyList<KeyValuePair<string, string>> inputHashes)
    {
        this.model = model;
        this.inputHashes = inputHashes;
        docs = new DocWriter(model);
    }

    /// <summary>Renders every output.</summary>
    /// <returns>Relative path (forward slashes) to file content, sorted by path.</returns>
    public SortedDictionary<string, string> RenderAll()
    {
        SortedDictionary<string, string> outputs = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [GeneratedFolder + "/Enums.g.cs"] = Render("Enums", model.Enums.Select(EnumView)),
            [GeneratedFolder + "/Bitflags.g.cs"] = Render("Bitflags", model.Bitflags.Select(BitflagView)),
            [GeneratedFolder + "/Structs.g.cs"] = Render("Structs", model.Structs.Select(StructView)),
            [GeneratedFolder + "/Callbacks.g.cs"] = Render("Callbacks", model.Callbacks.Where(c => c.Info != null).Select(CallbackView)),
            [GeneratedFolder + "/Functions.g.cs"] = Render("Functions", model.Functions.Select(BuildFunctionView)),
            [GeneratedFolder + "/Handles.g.cs"] = Render("Handles", model.Handles.Select(HandleView)),
            [GeneratedFolder + "/Constants.g.cs"] = Render("Constants", model.Constants.Select(BuildConstantView)),
            [GeneratedFolder + "/StructLayouts.g.cs"] = Render("StructLayouts", model.LayoutStructs.Select(s => new LayoutView { Name = s.CsName, CName = s.CName })),
            [ExpectedExportsPath] = Render("ExpectedExports", model.Functions.Select(f => f.CName).OrderBy(n => n, StringComparer.Ordinal), "#"),
        };
        return outputs;
    }

    /// <summary>The banner every generated file starts with.</summary>
    /// <param name="comment">The line-comment marker of the output language.</param>
    /// <returns>The banner lines.</returns>
    public string Banner(string comment)
    {
        List<string> lines = new List<string>
        {
            comment + " Generated by CodeBrix.WebGpu.BindingGenerator - DO NOT EDIT.",
            comment + " Regenerate: dotnet run --project tools/CodeBrix.WebGpu.BindingGenerator -- --write",
            comment + " Inputs (sha256):",
        };
        foreach (KeyValuePair<string, string> input in inputHashes)
        {
            lines.Add(comment + "   " + input.Value + "  " + input.Key);
        }

        return string.Join("\n", lines);
    }

    private string Render(string templateName, IEnumerable<object> items, string comment = "//")
    {
        string text = ReadTemplate(templateName);
        Template template = Template.Parse(text, templateName + ".scriban");
        if (template.HasErrors)
        {
            throw new InvalidOperationException("Template " + templateName + " does not parse: " + string.Join("; ", template.Messages));
        }

        ScriptObject globals = new ScriptObject();
        globals.Import(new TemplateModel { Banner = Banner(comment), Items = items.ToList() }, renamer: member => member.Name);
        TemplateContext context = new TemplateContext
        {
            AutoIndent = false,
            MemberRenamer = member => member.Name,
            LoopLimit = 1_000_000,
            LimitToString = 64 * 1024 * 1024,
            OutputLimit = 0,
            OnStringLimit = ScriptLimitBehavior.Throw,
            OnOutputLimit = ScriptLimitBehavior.Throw,
        };
        context.PushGlobal(globals);
        context.PushCulture(CultureInfo.InvariantCulture);
        return OutputNormalizer.Normalize(template.Render(context));
    }

    private static string ReadTemplate(string name)
    {
        Assembly assembly = typeof(CSharpRenderer).Assembly;
        using Stream stream = assembly.GetManifestResourceStream("Templates." + name + ".scriban")
                              ?? throw new InvalidOperationException("Missing embedded template " + name);
        using StreamReader reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    // ------------------------------------------------------------- views

    private static string Lines(IEnumerable<string> lines, int indent)
    {
        string pad = new string(' ', indent);
        return string.Join("\n", lines.Select(l => pad + l));
    }

    private object EnumView(ApiEnum value) => new TypeView
    {
        Name = value.CsName,
        Doc = Lines(docs.Summary(value.Doc, "Mirrors <c>" + value.CName + "</c>."), 0),
        Values = value.Values.Select(v => (object)new ValueView
        {
            Name = v.CsName,
            Value = "0x" + v.Value.ToString("X8", CultureInfo.InvariantCulture),
            Doc = Lines(docs.Summary(v.Doc, "Mirrors <c>" + v.CName + "</c>."), 4),
        }).ToList(),
    };

    private object BitflagView(ApiBitflag value) => new TypeView
    {
        Name = value.CsName,
        Doc = Lines(docs.Summary(value.Doc, "Mirrors <c>" + value.CName + "</c>."), 0),
        Values = value.Values.Select(v => (object)new ValueView
        {
            Name = v.CsName,
            Value = "0x" + v.Value.ToString("X16", CultureInfo.InvariantCulture),
            Doc = Lines(docs.Summary(v.Doc, "Mirrors <c>" + v.CName + "</c>."), 4),
        }).ToList(),
    };

    private object StructView(ApiStruct value) => new TypeView
    {
        Name = value.CsName,
        CName = value.CName,
        STypeValue = value.STypeValue,
        Doc = Lines(docs.Summary(value.Doc, "Mirrors <c>" + value.CName + "</c>.").Concat(DocWriter.Remarks("C type: <c>" + value.CName + "</c>.")), 0),
        Fields = value.Fields.Select(f => (object)new FieldView
        {
            Name = f.CsName,
            Type = f.CsType,
            Doc = Lines(docs.Summary(f.Doc, "Mirrors <c>" + value.CName + "." + f.CName + "</c>."), 4),
        }).ToList(),
    };

    private object CallbackView(ApiCallback value)
    {
        TypeView view = (TypeView)StructView(value.Info);
        view.Doc = Lines(
            docs.Summary(value.Doc, "The callback-info struct of <c>" + value.CName + "</c>.")
                .Concat(DocWriter.Remarks(
                    "C type: <c>" + value.Info.CName + "</c>. The callback is a Cdecl function: <c>"
                    + DocWriter.Escape(value.CSignature) + "</c>.")),
            0);
        return view;
    }

    private object BuildFunctionView(ApiFunction value)
    {
        string fallback = value.Synthesized switch
        {
            "add_ref" => "Adds one reference to the <see cref=\"" + value.OwnerCsName + "\" /> (<c>" + value.CName + "</c>).",
            "release" => "Releases one reference to the <see cref=\"" + value.OwnerCsName + "\" />; the object is destroyed when its last reference is released (<c>" + value.CName + "</c>).",
            _ => "Calls <c>" + value.CName + "</c>.",
        };

        List<string> lines = docs.Summary(value.Doc, fallback);
        foreach (ApiParameter parameter in value.Parameters)
        {
            lines.AddRange(docs.Param(parameter.CsName.TrimStart('@'), parameter.Doc, "The <c>" + parameter.CName + "</c> argument."));
        }

        if (value.ReturnType != "void") lines.AddRange(docs.Returns(value.ReturnDoc, "The value <c>" + value.CName + "</c> returns."));

        return new FunctionView
        {
            Name = value.CsName,
            CName = value.CName,
            ReturnType = value.ReturnType,
            Parameters = string.Join(", ", value.Parameters.Select(p => p.CsType + " " + p.CsName)),
            Doc = Lines(lines, 4),
        };
    }

    private object HandleView(ApiHandle value) => new TypeView
    {
        Name = value.CsName,
        CName = value.CName,
        Doc = Lines(docs.Summary(value.Doc, "A <c>" + value.CName + "</c> object handle.").Concat(DocWriter.Remarks("C type: <c>" + value.CName + "</c> (an opaque pointer).")), 0),
    };

    private object BuildConstantView(ApiConstant value) => new ConstantView
    {
        Doc = Lines(docs.Summary(value.Doc, "Mirrors <c>" + value.CName + "</c>."), 4),
        Declaration = (value.IsConst ? "public const " : "public static readonly ") + value.CsType + " " + value.CsName + " = " + value.CsValue + ";",
    };

    /// <summary>The template's root object.</summary>
    public sealed class TemplateModel
    {
        /// <summary>The banner.</summary>
        public string Banner { get; set; }

        /// <summary>The items the template iterates.</summary>
        public List<object> Items { get; set; }
    }

    /// <summary>A type (enum, bitflag, struct, handle) as the templates see it.</summary>
    public sealed class TypeView
    {
        /// <summary>The C# name.</summary>
        public string Name { get; set; }

        /// <summary>The C name.</summary>
        public string CName { get; set; }

        /// <summary>The doc comment lines.</summary>
        public string Doc { get; set; }

        /// <summary>For extension structs: the SType member, or null.</summary>
        public string STypeValue { get; set; }

        /// <summary>Enum / bitflag values.</summary>
        public List<object> Values { get; set; }

        /// <summary>Struct fields.</summary>
        public List<object> Fields { get; set; }
    }

    /// <summary>An enum or bitflag value.</summary>
    public sealed class ValueView
    {
        /// <summary>The member name.</summary>
        public string Name { get; set; }

        /// <summary>The value literal.</summary>
        public string Value { get; set; }

        /// <summary>The doc comment lines.</summary>
        public string Doc { get; set; }
    }

    /// <summary>A struct field.</summary>
    public sealed class FieldView
    {
        /// <summary>The field name.</summary>
        public string Name { get; set; }

        /// <summary>The field type.</summary>
        public string Type { get; set; }

        /// <summary>The doc comment lines.</summary>
        public string Doc { get; set; }
    }

    /// <summary>A function.</summary>
    public sealed class FunctionView
    {
        /// <summary>The C# name.</summary>
        public string Name { get; set; }

        /// <summary>The C symbol.</summary>
        public string CName { get; set; }

        /// <summary>The C# return type.</summary>
        public string ReturnType { get; set; }

        /// <summary>The parameter list.</summary>
        public string Parameters { get; set; }

        /// <summary>The doc comment lines.</summary>
        public string Doc { get; set; }
    }

    /// <summary>A constant.</summary>
    public sealed class ConstantView
    {
        /// <summary>The doc comment lines.</summary>
        public string Doc { get; set; }

        /// <summary>The full declaration.</summary>
        public string Declaration { get; set; }
    }

    /// <summary>A struct in the layout table.</summary>
    public sealed class LayoutView
    {
        /// <summary>The C# name.</summary>
        public string Name { get; set; }

        /// <summary>The C name.</summary>
        public string CName { get; set; }
    }
}
