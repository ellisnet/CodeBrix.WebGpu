using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace CodeBrix.WebGpu.BindingGenerator.Rendering;

/// <summary>
/// Renders wgpu-native-tools/codebrix-wgpu/applied-patches.txt: the names of wgpu-native-tools/patches/*.patch
/// (without the extension, in name order = apply order). codebrix-wgpu/build.rs compiles the list into the
/// <c>patches</c> member of <c>wgpuCodebrixGetBuildInfo</c> - the build scripts copy only wgpu-native/ and
/// codebrix-wgpu/ into their scratch tree, so the patches folder itself is not visible to the build.
/// </summary>
public static class PatchListRenderer
{
    /// <summary>The generated list, relative to the repository root.</summary>
    public const string OutputPath = "wgpu-native-tools/codebrix-wgpu/applied-patches.txt";

    /// <summary>The patches folder, relative to the repository root.</summary>
    public const string PatchesFolder = "wgpu-native-tools/patches";

    /// <summary>The patch names of a repository, in apply order.</summary>
    /// <param name="repositoryRoot">The repository root.</param>
    /// <returns>The names without <c>.patch</c>.</returns>
    public static List<string> PatchNames(string repositoryRoot)
    {
        string folder = Path.Combine(repositoryRoot, PatchesFolder);
        if (!Directory.Exists(folder)) return new List<string>();
        return Directory.GetFiles(folder, "*.patch")
            .Select(Path.GetFileNameWithoutExtension)
            .OrderBy(name => name, StringComparer.Ordinal)
            .ToList();
    }

    /// <summary>Renders the list file.</summary>
    /// <param name="names">The patch names, in apply order.</param>
    /// <returns>The file content.</returns>
    public static string Render(IEnumerable<string> names)
    {
        StringBuilder b = new StringBuilder();
        b.Append("# Generated by CodeBrix.WebGpu.BindingGenerator - DO NOT EDIT.\n");
        b.Append("# Regenerate: dotnet run --project tools/CodeBrix.WebGpu.BindingGenerator -- --write\n");
        b.Append("# The wgpu-native-tools/patches this library is built with, in apply order (build.rs -> the `patches`\n");
        b.Append("# member of wgpuCodebrixGetBuildInfo). One name per line; '#' lines are comments.\n");
        foreach (string name in names) b.Append(name).Append('\n');
        return b.ToString();
    }
}
