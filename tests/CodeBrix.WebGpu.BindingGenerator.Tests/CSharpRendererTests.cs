using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using CodeBrix.WebGpu.BindingGenerator.Model;
using CodeBrix.WebGpu.BindingGenerator.Rendering;
using SilverAssertions;
using Xunit;

namespace CodeBrix.WebGpu.BindingGenerator.Tests;

public class CSharpRendererTests
{
    // Set this environment variable to 1 to rewrite tests/.../Golden/*.golden from the current templates (then review
    // the diff). The .golden extension keeps the rendered C# out of this project's compilation.
    private const string UpdateVariable = "CODEBRIX_WEBGPU_UPDATE_GOLDEN";

    private static SortedDictionary<string, string> RenderFixture()
    {
        ApiModel model = TestPaths.FixtureModel();
        List<KeyValuePair<string, string>> hashes = new List<KeyValuePair<string, string>>
        {
            new KeyValuePair<string, string>("Fixtures/webgpu.yml", new string('a', 64)),
            new KeyValuePair<string, string>("Fixtures/ext.yml", new string('b', 64)),
        };
        return new CSharpRenderer(model, hashes).RenderAll();
    }

    public static TheoryData<string> GoldenFiles() =>
        new TheoryData<string>(RenderFixture().Keys.Select(Path.GetFileName));

    [Theory]
    [MemberData(nameof(GoldenFiles))]
    public void RenderAll_matches_the_golden_file(string fileName)
    {
        //Arrange
        string rendered = RenderFixture().Single(pair => Path.GetFileName(pair.Key) == fileName).Value;
        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
        {
            File.WriteAllText(Path.Combine(TestPaths.RepositoryRoot, "tests", "CodeBrix.WebGpu.BindingGenerator.Tests", "Golden", fileName + ".golden"), rendered);
            return;
        }

        //Act
        string golden = File.ReadAllText(TestPaths.Golden(fileName + ".golden"));

        //Assert
        rendered.Should().Be(golden);
    }

    [Fact]
    public void RenderAll_is_deterministic()
    {
        //Act
        SortedDictionary<string, string> first = RenderFixture();
        SortedDictionary<string, string> second = RenderFixture();

        //Assert
        second.Should().Equal(first);
    }

    [Fact]
    public void RenderAll_starts_every_output_with_the_banner()
    {
        //Act
        SortedDictionary<string, string> outputs = RenderFixture();

        //Assert
        foreach (KeyValuePair<string, string> output in outputs)
        {
            string marker = output.Key.EndsWith(".txt", StringComparison.Ordinal) ? "#" : "//";
            output.Value.Should().StartWith(marker + " Generated by CodeBrix.WebGpu.BindingGenerator - DO NOT EDIT.");
            output.Value.Should().Contain(new string('a', 64) + "  Fixtures/webgpu.yml");
        }
    }

    [Fact]
    public void RenderAll_lists_every_export_sorted_after_the_banner()
    {
        //Act
        string[] symbols = RenderFixture()[CSharpRenderer.ExpectedExportsPath]
            .Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Where(line => !line.StartsWith('#'))
            .ToArray();

        //Assert
        symbols.Should().Equal(symbols.OrderBy(s => s, StringComparer.Ordinal));
        symbols.Should().Contain("wgpuThingAddRef");
        symbols.Should().HaveCount(8);
    }

    [Fact]
    public void RenderAll_uses_lf_line_endings_only()
        => RenderFixture().Values.Should().OnlyContain(text => !text.Contains('\r'));
}
